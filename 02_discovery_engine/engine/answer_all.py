"""Answer all of the brief's discovery questions from the tagged sample -> DISCOVERY_ANSWERS.md.

    python -m engine.answer_all
"""
from pathlib import Path

import pandas as pd
import yaml

from common.llm import describe
from engine import analyze, ask, sources, tag

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text())
    recs = tag.prefilter(sources.load_local(cfg.get("sources")))
    pop = pd.Series([r["source"] for r in recs]).value_counts().to_dict()
    if cfg.get("sample_per_source"):
        recs = tag.stratified_sample(recs, cfg["sample_per_source"], seed=cfg.get("seed", 42))
    df = analyze.build_frame(recs, tag.load_cache(), pop)
    out = [f"# Discovery engine: answers to the brief's questions\n\n"
           f"Generated by `engine/ask.py` with `{describe('smart')}` over the tagged sample "
           f"({len(df)} items, {int(df['relevant'].sum())} relevant).\n\n"
           "Each answer cites corpus item ids; look them up in the dashboard's *Evidence explorer* or in "
           "`data/store/*.jsonl`. The engine declines when it finds fewer than 5 evidence items. A grounding "
           "check lists any cited id that is not in the evidence.\n\n"
           "These answers are qualitative: each reads the 40 most relevant tagged posts, so \"well supported\" "
           "means within those posts. How common each reason is comes from the tagged counts instead "
           "(deck slide 3: failed payments 29% of stop signals, markets 15%).\n"]
    for q in ask.PRESETS:
        r = ask.answer(df, q)
        out.append(f"## {q}\n\n{r['answer']}\n\n*Evidence items: {len(r['evidence'])} · cited: {r.get('cited', '-')} · "
                   f"unknown ids: {len(r.get('hallucinated_ids', []))}*\n")
        print(f"{q[:60]:<60} evidence={len(r['evidence'])} cited={r.get('cited')} unknown={r.get('hallucinated_ids')}")
    (ROOT / "DISCOVERY_ANSWERS.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
